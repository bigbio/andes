//! The Methods paragraph of the run report, ready for a paper, and its references from the
//! citation registry `docs/citations.yaml`. Each citation is numbered `[n]` in order of first use.

use output::Reference;

/// The citation registry, built into the binary so the report needs no file at run time.
const REGISTRY_YAML: &str = include_str!("../../../../../../docs/citations.yaml");

/// What the Methods paragraph states about the run.
pub(crate) struct MethodsFacts<'a> {
    pub(crate) version: &'a str,
    pub(crate) database: &'a str,
    pub(crate) enzyme: &'a str,
    pub(crate) missed_cleavages: u32,
    pub(crate) precursor_tolerance: &'a str,
    pub(crate) fragment_tolerance: &'a str,
    pub(crate) fixed_mods: &'a [String],
    pub(crate) variable_mods: &'a [String],
    pub(crate) decoys: &'a str,
    pub(crate) rescored: bool,
    pub(crate) psm_fdr: Option<f64>,
    pub(crate) protein_fdr: Option<f64>,
}

/// A piece of a sentence: text, or a citation of a registry key.
enum Part {
    Text(String),
    Cite(&'static str),
}

fn text(s: impl Into<String>) -> Part {
    Part::Text(s.into())
}

/// The sentences of the paragraph; a sentence whose condition is false is left out.
fn sentences(f: &MethodsFacts) -> Vec<Vec<Part>> {
    let mut out = vec![vec![
        text(format!("Spectra were searched with andes {} ", f.version)),
        Part::Cite("kim2014_msgfplus"),
        text(format!(
            " against {} ({}, up to {} missed cleavages), with a precursor tolerance of {} and a \
             fragment tolerance of {}.",
            f.database, f.enzyme, f.missed_cleavages, f.precursor_tolerance, f.fragment_tolerance
        )),
    ]];
    if !f.fixed_mods.is_empty() {
        out.push(vec![text(format!("Fixed modifications: {}.", f.fixed_mods.join(", ")))]);
    }
    if !f.variable_mods.is_empty() {
        out.push(vec![text(format!(
            "Variable modifications: {}.",
            f.variable_mods.join(", ")
        ))]);
    }
    out.push(vec![
        text(format!("Decoys were generated by {} ", f.decoys)),
        Part::Cite("elias2007_target_decoy"),
        text("."),
    ]);
    if f.rescored {
        let cut = f
            .psm_fdr
            .map_or_else(String::new, |q| format!(" and filtered at {q} PSM-level FDR"));
        out.push(vec![
            text("PSMs were rescored with Percolator "),
            Part::Cite("kall2007_percolator"),
            text(format!("{cut}.")),
        ]);
    }
    if let Some(q) = f.protein_fdr {
        out.push(vec![
            text(format!(
                "Protein groups were inferred and filtered at {q} protein-level FDR with the \
                 picked approach "
            )),
            Part::Cite("savitski2015_picked_fdr"),
            text("."),
        ]);
    }
    out
}

/// The paragraph with each citation as `[n]`, numbered in order of first use, and the cited
/// keys in that order.
pub(crate) fn methods_paragraph(f: &MethodsFacts) -> (String, Vec<&'static str>) {
    let mut keys: Vec<&'static str> = Vec::new();
    let mut rendered: Vec<String> = Vec::new();
    for sentence in sentences(f) {
        let mut s = String::new();
        for part in sentence {
            match part {
                Part::Text(t) => s.push_str(&t),
                Part::Cite(key) => {
                    let n = match keys.iter().position(|k| *k == key) {
                        Some(i) => i + 1,
                        None => {
                            keys.push(key);
                            keys.len()
                        }
                    };
                    s.push_str(&format!("[{n}]"));
                }
            }
        }
        rendered.push(s);
    }
    (rendered.join(" "), keys)
}

#[derive(serde::Deserialize)]
struct Entry {
    key: String,
    authors: String,
    title: String,
    year: u32,
    journal: Option<String>,
    doi: Option<String>,
    url: Option<String>,
}

/// The references of `keys`, in order, from the registry. A key that is not in it reads
/// `unknown citation key`.
pub(crate) fn references(keys: &[&str]) -> Vec<Reference> {
    let entries: Vec<Entry> = serde_yaml::from_str(REGISTRY_YAML).unwrap_or_default();
    keys.iter()
        .map(|&key| {
            let text = entries.iter().find(|e| e.key == key).map_or_else(
                || "unknown citation key".to_string(),
                |e| {
                    let mut t = format!("{} ({}). {}.", e.authors, e.year, e.title);
                    if let Some(j) = &e.journal {
                        t.push_str(&format!(" {j}."));
                    }
                    match (&e.doi, &e.url) {
                        (Some(doi), _) => t.push_str(&format!(" doi:{doi}")),
                        (None, Some(url)) => t.push_str(&format!(" {url}")),
                        (None, None) => {}
                    }
                    t
                },
            );
            Reference {
                key: key.to_string(),
                text,
            }
        })
        .collect()
}

/// Ubiquitin-like modifiers that leave a Gly-Gly remnant (+114.042927 Da) on
/// the modified lysine after tryptic digestion. UniProt annotates them as an
/// interchain `cross-link` with this description prefix and the modifier
/// name in the closing parenthesis.
pub(crate) const GLYGLY_CROSSLINK_PREFIX: &str =
    "Glycyl lysine isopeptide (Lys-Gly) (interchain with G-Cter in ";
pub(crate) const GLYGLY_MODIFIERS: &[&str] = &["ubiquitin)", "NEDD8)", "ISG15)"];
/// Gly-Gly remnant mass (Unimod 121).
pub(crate) const GLYGLY_MASS: f64 = 114.042927;

/// `(target residue, mass)` of the UniProt modification named `name`, after
/// the cleanup UniProt descriptions need (see [`clean_description`]).
pub(crate) fn ptm_mass(name: &str) -> Option<(u8, f64)> {
    PTM_MASSES
        .binary_search_by(|(n, _, _)| (*n).cmp(name))
        .ok()
        .map(|i| (PTM_MASSES[i].1, PTM_MASSES[i].2))
}

/// The modification name inside a UniProt feature description: drops a
/// leading `(Microbial infection) ` and anything after the first `;`
/// (`Phosphoserine; by PKA`, `N6-acetyllysine; alternate`), as OpenMS'
/// UniPEFF does.
pub(crate) fn clean_description(description: &str) -> &str {
    let d = description
        .strip_prefix("(Microbial infection) ")
        .unwrap_or(description);
    d.split(';').next().unwrap_or(d).trim()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_for_binary_search() {
        assert!(PTM_MASSES.windows(2).all(|w| w[0].0 < w[1].0));
    }

    #[test]
    fn common_modifications_resolve() {
        assert_eq!(ptm_mass("Phosphoserine"), Some((b'S', 79.966331)));
        assert_eq!(ptm_mass("N6-acetyllysine"), Some((b'K', 42.010565)));
        assert_eq!(
            ptm_mass("Pyrrolidone carboxylic acid"),
            Some((b'Q', -17.026549))
        );
        assert_eq!(
            ptm_mass("N-linked (GlcNAc) asparagine"),
            Some((b'N', 203.079373))
        );
        // A glycan of unknown composition has no single mass.
        assert_eq!(ptm_mass("N-linked (GlcNAc...) asparagine"), None);
    }

    #[test]
    fn descriptions_are_cleaned_like_unipeff() {
        assert_eq!(
            clean_description("Phosphoserine; by CDK5 and CDK7"),
            "Phosphoserine"
        );
        assert_eq!(
            clean_description("(Microbial infection) N6-acetyllysine; alternate"),
            "N6-acetyllysine"
        );
        assert_eq!(clean_description("Phosphothreonine"), "Phosphothreonine");
    }
}

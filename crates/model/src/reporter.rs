//! Reporter-ion channels of the isobaric labels (TMT, TMTpro, iTRAQ): the one table that label
//! detection in `input` and quantification in `quant` both read.

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Channel {
    pub name: &'static str,
    pub mz: f64,
}

pub const fn ch(name: &'static str, mz: f64) -> Channel {
    Channel { name, mz }
}


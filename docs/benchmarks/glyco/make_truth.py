#!/usr/bin/env python3
"""Convert a published glyco reference into this harness's canonical truth table.

    make_truth.py pglyco2  <*-FDR.txt> ...      > truth.tsv
    make_truth.py strucgp  <*_result.xlsx> ...  > truth.tsv
    make_truth.py msfragger <psm.tsv> [RUN-PREFIX]  > truth.tsv
    make_truth.py maxquant  <msms.txt> [RUN-PREFIX]  > truth.tsv

WHY THIS EXISTS
Reference identifications ship in whatever format the original engine emitted: pGlyco2 in
plain TSV, StrucGP in `.xlsx`, MSFragger-Glyco in a Philosopher-filtered `psm.tsv`,
MaxQuant in `msms.txt`. Re-parsing those
every time is slow, needs the multi-GB originals, and re-invites the two mistakes that have
already produced wrong numbers here:

  * counting the reference engine's own DECOYS as truth, and
  * using its PRE-FDR output as though it were its confident call set.

Each reader below applies the correct decoy and FDR filter for its format, and records what
it applied in the output header. The results are small (a few thousand rows), so the
generated tables are committed under `truth/` and read directly — no re-download.

CANONICAL COLUMNS
    run       source run/file stem, so pooled fractions stay distinguishable
    scan      MS2 scan number
    charge    precursor charge
    peptide   BARE backbone, uppercase, no modifications
    glycan    composition as the source reports it ('' if unavailable)
    glycosite 1-based site within the peptide ('' if unavailable)

One row per (run, scan): a reference may list several proteins or glycoforms for one
spectrum, and counting those as separate truth entries inflated a truth set from 629
spectra to 1,068 rows once already.
"""
import csv, os, re, sys


def emit(rows, source, filt):
    w = csv.writer(sys.stdout, delimiter="\t", lineterminator="\n")
    print(f"# source: {source}")
    print(f"# filter: {filt}")
    print(f"# one row per (run, scan); generated by make_truth.py")
    # Readers may add a 7th field (MaxQuant's modified sequence, for a localisation
    # comparison). Widen the header only when one actually did, so the glyco tables keep
    # their existing six columns byte-for-byte.
    extra = any(len(r) > 6 for r in rows)
    w.writerow(["run", "scan", "charge", "peptide", "glycan", "glycosite"]
               + (["modified_peptide"] if extra else []))
    seen = set()
    n = 0
    for r in rows:
        key = (r[0], r[1])
        if key in seen:
            continue
        seen.add(key)
        w.writerow(r if not extra else (list(r) + [""] * (7 - len(r)))[:7])
        n += 1
    print(f"# rows: {n}", file=sys.stderr)


def pglyco2(paths):
    """pGlyco2 `*-FDR.txt`. 'J' marks the glycosylated asparagine -> N.

    The Glycan column is a count vector in the order `Hex HexNAc NeuAc NeuGc Fuc`. That
    order is not assumed: for every file, every accepted row's vector is summed under all
    120 orderings of the five monosaccharide masses and compared with pGlyco2's own
    GlyMass column. The assumed order must be the unique best and must reproduce GlyMass
    on at least 99% of rows, or the reader refuses the file. Measured on the T-1 fraction
    of each tissue it reproduces GlyMass on 3,995/3,995 (liver), 3,142/3,142 (lung) and
    1,759/1,759 (heart) rows; every other ordering fails on hundreds.

    WHY THE CHECK EXISTS. Two earlier readings were wrong and each looked verified:
      * `Hex HexNAc Fuc NeuAc NeuGc` was "verified against GlyMass" on ~200 mostly
        non-sialylated, non-fucosylated rows -- where the order of the last three fields
        does not change the mass, so the check could not see the error. It rotated three
        labels: what it called Fuc was NeuAc, what it called NeuAc was NeuGc, and what it
        called NeuGc was Fuc. On a CMAH-competent mouse sample that inverts the dominant
        sialic acid in the committed tables.
      * A first correction moved only NeuGc into place, on a test restricted to sialylated
        rows that could not distinguish Fuc from NeuAc; the rows it left unexplained were
        exactly the fucosylated ones (NeuAc - Fuc = 145.037 Da).
    The exhaustive check below is what a partial check could not be: it cannot be
    satisfied by a wrong order on any file that carries fucose or sialic acid at all."""
    MASS = {"Hex": 162.052824, "HexNAc": 203.079373, "Fuc": 146.057909,
            "NeuAc": 291.095417, "NeuGc": 307.090331}
    ORDER = ("Hex", "HexNAc", "NeuAc", "NeuGc", "Fuc")
    import itertools
    out = []
    for p in paths:
        run = os.path.basename(p).replace("-FDR.txt", "")
        vectors = []
        for r in csv.DictReader(open(p), delimiter="\t"):
            if (r.get("GlyDecoy") or "0") not in ("0", "") or (r.get("PepDecoy") or "0") not in ("0", ""):
                continue
            try:
                if float(r.get("TotalFDR", 1)) > 0.01:
                    continue
            except ValueError:
                continue
            spec = r.get("GlySpec", "").split(".")
            if len(spec) < 4:
                continue
            pep = re.sub(r"[^A-Z]", "", r.get("Peptide", "").upper().replace("J", "N"))
            v = (r.get("Glycan") or "").split()
            gly = ""
            if len(v) == 5:
                h, n, a, g, f = v
                gly = f"HexNAc{n}Hex{h}Fuc{f}NeuAc{a}NeuGc{g}"
                try:
                    vectors.append((tuple(map(int, v)), float(r.get("GlyMass"))))
                except (TypeError, ValueError):
                    pass
            out.append([run, spec[1], spec[3], pep, gly, r.get("GlySite", "")])
        if vectors:
            def hits(order):
                return sum(1 for v, gm in vectors
                           if abs(sum(c * MASS[m] for c, m in zip(v, order)) - gm) < 0.02)
            scored = sorted(((hits(o), o) for o in itertools.permutations(MASS)), reverse=True)
            best_n, best_o = scored[0]
            assumed = hits(ORDER)
            # `sorted` breaks a tied hit count by the order tuple, so `best_o == ORDER` alone
            # would accept a file on which another ordering fits equally well; require that
            # exactly one ordering reaches the best count.
            unique_best = sum(1 for n, _ in scored if n == best_n) == 1
            if best_o != ORDER or not unique_best or assumed < 0.99 * len(vectors):
                sys.exit(f"{p}: Glycan column order is not uniquely {' '.join(ORDER)} -- best fit is "
                         f"{' '.join(best_o)} ({best_n}/{len(vectors)}, "
                         f"{sum(1 for n, _ in scored if n == best_n)} ordering(s) at that count), "
                         f"assumed order fits {assumed}/{len(vectors)}. Refusing to emit a mislabelled table.")
            print(f"# {os.path.basename(p)}: Glycan order {' '.join(ORDER)} reproduces GlyMass on "
                  f"{assumed}/{len(vectors)} rows (next-best ordering: {scored[1][0]})", file=sys.stderr)
    return out, "GlyDecoy=0 AND PepDecoy=0 AND TotalFDR<=0.01"


def strucgp(paths):
    """StrucGP `*_result.xlsx` (already FDR-filtered by the depositors)."""
    import openpyxl
    out = []
    for p in paths:
        run = os.path.basename(p).replace("_result.xlsx", "")
        ws = openpyxl.load_workbook(p, read_only=True)[
            openpyxl.load_workbook(p, read_only=True).sheetnames[0]]
        it = ws.iter_rows(values_only=True)
        hdr = [str(h) for h in next(it)]
        ix = {h: i for i, h in enumerate(hdr)}
        for row in it:
            if not row or row[ix.get("MS2Scan", 0)] is None:
                continue
            out.append([run, row[ix["MS2Scan"]], row[ix.get("PrecursorCharge", 0)],
                        re.sub(r"[^A-Z]", "", str(row[ix["PeptideSequence"]]).upper()),
                        row[ix.get("GlycanComposition", 0)] or "",
                        row[ix.get("Glycosite_Position", 0)] or ""])
    return out, "as published (depositor-filtered result table)"


def msfragger(paths):
    """Philosopher-filtered MSFragger-Glyco `psm.tsv` (already at the depositors' PSM FDR;
    decoys removed). The glycan is the `Observed Modifications` column, e.g.
    `Hex(5)HexNAc(2)(1216.422863)`; several candidates may be listed comma-separated,
    best first, and the first is kept. Rows whose observed modification is not made only
    of HexNAc/Hex/dHex/NeuAc/NeuGc (chemical mods, isotope labels, Kdn, Pent, HexA...) are
    NOT glycopeptides for this benchmark and are dropped. An optional second argument
    keeps only runs whose name starts with it (`MouseLiver`)."""
    prefix = paths[1] if len(paths) > 1 else ""
    allowed = {"HexNAc": "n", "Hex": "h", "dHex": "f", "NeuAc": "a", "NeuGc": "g"}
    out, dropped = [], 0
    with open(paths[0]) as fh:
        for r in csv.DictReader(fh, delimiter="\t"):
            om = (r.get("Observed Modifications") or "").split(",")[0].split("%")[0].strip()
            if not om:
                continue
            counts = {"n": 0, "h": 0, "f": 0, "a": 0, "g": 0}
            ok = True
            for name, num in re.findall(r"([A-Za-z:>\-\d]+)\((\d+)\)", om):
                if name not in allowed:
                    ok = False
                    break
                counts[allowed[name]] += int(num)
            if not ok or counts["n"] == 0:
                dropped += 1
                continue
            spec = r["Spectrum"]                      # MouseLiver-Z-T-1.01954.01954.3
            run, scan = spec.split(".")[0], spec.split(".")[1].lstrip("0") or "0"
            if prefix and not run.startswith(prefix):
                continue
            gly = "HexNAc{n}Hex{h}Fuc{f}NeuAc{a}NeuGc{g}".format(**counts)
            out.append([run, scan, r.get("Charge", ""),
                        re.sub(r"[^A-Z]", "", r["Peptide"].upper()), gly, ""])
    print(f"# msfragger: dropped {dropped} rows whose observed modification is not an N-glycan",
          file=sys.stderr)
    return out, "Philosopher-filtered psm.tsv as deposited; Observed Modifications parsed as HexNAc/Hex/dHex/NeuAc/NeuGc only"


def maxquant(paths):
    """MaxQuant `msms.txt` (one row per identified MS/MS). Used for the phospho benchmark,
    where the deposited search covers many runs, so a RUN-PREFIX argument is normally
    required to keep only the runs actually searched -- otherwise the reference counts
    spectra from files nobody searched and every miss looks like an andes failure.

    Filters: `Reverse` blank (MaxQuant flags decoys with `+`), and PEP <= 0.01. MaxQuant's
    own FDR is applied upstream at 1% peptide and site level, so the PEP cut is a second,
    per-spectrum guard rather than the primary filter.

    The `modified_peptide` column keeps MaxQuant's `Modified sequence` verbatim, so a
    localisation comparison can be made later; the `peptide` column is the bare backbone,
    matching every other reader here."""
    prefix = paths[1] if len(paths) > 1 else ""
    out, dropped = [], 0
    with open(paths[0]) as fh:
        rd = csv.DictReader(fh, delimiter="\t")
        need = {"Raw file", "Scan number", "Sequence", "Modified sequence"}
        missing = need - set(rd.fieldnames or [])
        if missing:
            sys.exit(f"{paths[0]}: msms.txt is missing columns {sorted(missing)}")
        for r in rd:
            run = r["Raw file"]
            if prefix and not run.startswith(prefix):
                continue
            if (r.get("Reverse") or "").strip():
                dropped += 1
                continue
            try:
                if float(r.get("PEP") or 1.0) > 0.01:
                    dropped += 1
                    continue
            except ValueError:
                dropped += 1
                continue
            out.append([run, r["Scan number"], r.get("Charge", ""),
                        re.sub(r"[^A-Z]", "", r["Sequence"].upper()),
                        "", "", r["Modified sequence"].strip("_")])
    print(f"# maxquant: dropped {dropped} decoy/low-confidence rows", file=sys.stderr)
    return out, "MaxQuant msms.txt as deposited; Reverse blank and PEP <= 0.01"


READERS = {"pglyco2": pglyco2, "strucgp": strucgp, "msfragger": msfragger,
           "maxquant": maxquant}

if __name__ == "__main__":
    if len(sys.argv) < 3 or sys.argv[1] not in READERS:
        sys.exit(__doc__)
    rows, filt = READERS[sys.argv[1]](sys.argv[2:])
    emit(rows, f"{sys.argv[1]}: " + ", ".join(os.path.basename(p) for p in sys.argv[2:]), filt)

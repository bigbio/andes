#!/usr/bin/env python3
"""Convert a published glyco reference into this harness's canonical truth table.

    make_truth.py pglyco2  <*-FDR.txt> ...      > truth.tsv
    make_truth.py byonic   <*.byrslt>  ...      > truth.tsv
    make_truth.py strucgp  <*_result.xlsx> ...  > truth.tsv

WHY THIS EXISTS
Reference identifications ship in whatever format the original engine emitted: pGlyco2 in
plain TSV, Byonic in a proprietary SQLite `.byrslt`, StrucGP in `.xlsx`. Re-parsing those
every time is slow, needs the multi-GB originals, and re-invites the two mistakes that have
already produced wrong numbers here:

  * counting the reference engine's own DECOYS as truth, and
  * using its PRE-FDR output as though it were its confident call set.

Each reader below applies the correct decoy and FDR filter for its format, and records what
it applied in the output header. The results are small (a few thousand rows), so the
generated tables are committed under `truth/` and read directly — no re-download.

CANONICAL COLUMNS
    run       source run/file stem, so pooled fractions stay distinguishable
    scan      MS2 scan number
    charge    precursor charge
    peptide   BARE backbone, uppercase, no modifications
    glycan    composition as the source reports it ('' if unavailable)
    glycosite 1-based site within the peptide ('' if unavailable)

One row per (run, scan): a reference may list several proteins or glycoforms for one
spectrum, and counting those as separate truth entries inflated a truth set from 629
spectra to 1,068 rows once already.
"""
import csv, os, re, sqlite3, sys


def emit(rows, source, filt):
    w = csv.writer(sys.stdout, delimiter="\t", lineterminator="\n")
    print(f"# source: {source}")
    print(f"# filter: {filt}")
    print(f"# one row per (run, scan); generated by make_truth.py")
    w.writerow(["run", "scan", "charge", "peptide", "glycan", "glycosite"])
    seen = set()
    n = 0
    for r in rows:
        key = (r[0], r[1])
        if key in seen:
            continue
        seen.add(key)
        w.writerow(r)
        n += 1
    print(f"# rows: {n}", file=sys.stderr)


def pglyco2(paths):
    """pGlyco2 `*-FDR.txt`. 'J' marks the glycosylated asparagine -> N."""
    out = []
    for p in paths:
        run = os.path.basename(p).replace("-FDR.txt", "")
        for r in csv.DictReader(open(p), delimiter="\t"):
            if (r.get("GlyDecoy") or "0") not in ("0", "") or (r.get("PepDecoy") or "0") not in ("0", ""):
                continue
            try:
                if float(r.get("TotalFDR", 1)) > 0.01:
                    continue
            except ValueError:
                continue
            spec = r.get("GlySpec", "").split(".")
            if len(spec) < 4:
                continue
            pep = re.sub(r"[^A-Z]", "", r.get("Peptide", "").upper().replace("J", "N"))
            out.append([run, spec[1], spec[3], pep,
                        (r.get("Glycan") or "").strip(), r.get("GlySite", "")])
    return out, "GlyDecoy=0 AND PepDecoy=0 AND TotalFDR<=0.01"


def byonic(paths):
    """Byonic `.byrslt` is SQLite. PQMs is the filtered set; keep target rows at 1% FDR
    carrying an N-glycan ('ngly' modification class)."""
    out = []
    for p in paths:
        run = os.path.basename(p).replace(".byrslt", "")
        con = sqlite3.connect(p)
        cur = con.cursor()
        ngly = {i for (i,) in cur.execute("select Id from Modifications where Classification='ngly'")}
        links = {}
        for pqm, mod in cur.execute("select PQMsId, ModificationsId from PQMsPeptideToModifications"):
            links.setdefault(pqm, []).append(mod)
        scan = {}
        for qid, sl in cur.execute("select Id, ScanNumberList from Queries"):
            m = re.search(r"scan=(\d+)", sl or "")
            if m:
                scan[qid] = m.group(1)
        for pid, qid, pep, ch in cur.execute(
                "select Id, QueriesId, Peptide, Charge from PQMs "
                "where IsDecoy=0 and FalseDiscoveryRate1<=0.01"):
            if not any(m in ngly for m in links.get(pid, [])):
                continue
            if qid not in scan:
                continue
            out.append([run, scan[qid], ch, re.sub(r"[^A-Z]", "", (pep or "").upper()), "", ""])
        con.close()
    return out, "IsDecoy=0 AND FalseDiscoveryRate1<=0.01 AND has an 'ngly' modification"


def strucgp(paths):
    """StrucGP `*_result.xlsx` (already FDR-filtered by the depositors)."""
    import openpyxl
    out = []
    for p in paths:
        run = os.path.basename(p).replace("_result.xlsx", "")
        ws = openpyxl.load_workbook(p, read_only=True)[
            openpyxl.load_workbook(p, read_only=True).sheetnames[0]]
        it = ws.iter_rows(values_only=True)
        hdr = [str(h) for h in next(it)]
        ix = {h: i for i, h in enumerate(hdr)}
        for row in it:
            if not row or row[ix.get("MS2Scan", 0)] is None:
                continue
            out.append([run, row[ix["MS2Scan"]], row[ix.get("PrecursorCharge", 0)],
                        re.sub(r"[^A-Z]", "", str(row[ix["PeptideSequence"]]).upper()),
                        row[ix.get("GlycanComposition", 0)] or "",
                        row[ix.get("Glycosite_Position", 0)] or ""])
    return out, "as published (depositor-filtered result table)"


READERS = {"pglyco2": pglyco2, "byonic": byonic, "strucgp": strucgp}

if __name__ == "__main__":
    if len(sys.argv) < 3 or sys.argv[1] not in READERS:
        sys.exit(__doc__)
    rows, filt = READERS[sys.argv[1]](sys.argv[2:])
    emit(rows, f"{sys.argv[1]}: " + ", ".join(os.path.basename(p) for p in sys.argv[2:]), filt)
